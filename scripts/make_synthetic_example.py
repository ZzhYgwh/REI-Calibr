#!/usr/bin/env python3
"""Generate a small radar-only sequence for smoke testing the pipeline."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/example"))
    parser.add_argument("--duration", type=float, default=24.0)
    parser.add_argument("--reference-rate", type=float, default=100.0)
    parser.add_argument("--radar-rate", type=float, default=20.0)
    parser.add_argument("--tau", type=float, default=0.35, help="Radar minus body time offset in seconds.")
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    t_body = np.arange(0.0, args.duration, 1.0 / args.reference_rate)

    v_body = np.column_stack(
        [
            0.55 * np.sin(0.35 * t_body),
            0.35 * np.cos(0.27 * t_body),
            0.12 * np.sin(0.19 * t_body),
        ]
    )
    omega_body = np.column_stack(
        [
            0.90 * np.sin(0.55 * t_body),
            0.55 * np.cos(0.43 * t_body),
            0.40 * np.sin(0.71 * t_body + 0.4),
        ]
    )

    p_body_radar = np.array([0.12, -0.03, 0.08])
    rotation_body_radar = np.eye(3)
    velocity_radar_frame = (v_body + np.cross(omega_body, p_body_radar)) @ rotation_body_radar

    t_radar = np.arange(0.0, args.duration, 1.0 / args.radar_rate)
    velocity_radar = np.column_stack(
        [
            np.interp(t_radar, t_body, velocity_radar_frame[:, axis])
            for axis in range(3)
        ]
    )
    velocity_radar += rng.normal(scale=0.01, size=velocity_radar.shape)
    t_radar = t_radar + args.tau

    args.output.mkdir(parents=True, exist_ok=True)
    gt = np.column_stack([t_body, v_body, omega_body])
    radar = np.column_stack([t_radar, velocity_radar])
    np.savetxt(
        args.output / "gt.twist",
        gt,
        fmt="%.9f",
        delimiter=" ",
        header="timestamp,vx,vy,vz,wx,wy,wz",
        comments="",
    )
    np.savetxt(
        args.output / "radar_vel.tum",
        radar,
        fmt="%.9f",
        delimiter=" ",
        header="timestamp,vx,vy,vz",
        comments="",
    )
    truth = {
        "p_body_radar_m": p_body_radar.tolist(),
        "R_body_radar": rotation_body_radar.tolist(),
        "tau_radar_minus_body_sec": args.tau,
        "note": "Synthetic sequence generated by scripts/make_synthetic_example.py",
    }
    (args.output / "synthetic_ground_truth.json").write_text(
        json.dumps(truth, indent=2) + "\n", encoding="utf-8"
    )
    print(f"Wrote synthetic sequence to {args.output}")
    print(json.dumps(truth, indent=2))


if __name__ == "__main__":
    main()
